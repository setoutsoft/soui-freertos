/*
 * app_main.cpp -- ESP-IDF entry point for the SOUI4/FreeRTOS port.
 *
 * This is <soui-freertos>/soui_sim/main.cpp with the shell replaced:
 *
 *   soui_sim/main.cpp                     this file
 *   ------------------------------------  ----------------------------------
 *   SimHalInit()                          soui_board_init()
 *   SAppCfg::DoConfig() + InitXmlNamedID  identical -- render-gdi (cairo),
 *                                         imgdecoder-stb, one windres PE blob
 *                                         serving the system theme and the app
 *   xTaskCreate(..., 1<<19, ...)          xTaskCreatePinnedToCore(..., 49152)
 *   vTaskStartScheduler()                 supplied by IDF startup
 *   vTaskEndScheduler() / ExitThread()    never called (IDF has no shutdown)
 *   _exit(s_appRc)                        task deletes itself when the window closes
 *   SimHalPumpEvents / RenderIfDirty      soui_board_poll_touch + swinxFbPresent
 *   SDL window                            ILI9341V over SPI (soui_board_esp32.cpp)
 *
 * Two resource sets are compiled into the image by windres (main.rc ->
 * PE-COFF -> .rodata.embedded, see cmake/soui_res.cmake) and served at runtime
 * by SResProviderPE through swinx's WindResResourceParser:
 *   * the SOUI system theme (soui-sys-resource-light) -> SYS_XML_SKIN /
 *     THEME_COLOR / all sys_*.svg, i.e. the _skin.sys.* skins the caption and
 *     controls ask for,
 *   * the application uires (this project's uires/ directory: uidef init.xml,
 *     values, layout, png/svg test images).
 *
 * This is the same resource path a Windows SOUI app takes -- no C array is
 * generated, and editing a layout/image/string only needs a rebuild.
 *
 * The message pump uses IMessageLoop::OnMsg() rather than a raw
 * TranslateMessage/DispatchMessage pair, exactly as soui_sim/main.cpp does:
 * SOUI's keyboard filters (drop-down navigation, focus routing) live in
 * PreTranslateMessage, which OnMsg() calls.
 */
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"

#include "esp_log.h"
#include "esp_timer.h"

// Which statically linked components SAppCfg's SComMgr2 may name.  This MUST
// be defined before <SAppCfg.h> is first seen: commgr2.h defaults SCOM_MASK to
// "all components", and every enabled bit puts a call to e.g.
// RENDER_SKIA::SCreateInstance() into the generated code.  render-skia /
// scriptmodule-lua / translator / log4z are not part of this firmware, so the
// default mask would fail at link time instead of at call time.
#include <commask.h>
#define SCOM_MASK (scom_mask_render_gdi | scom_mask_imgdecoder_stb)

#include <souistd.h>
#include <SAppCfg.h> // SApplication + SAppCfg bring-up (wizard/CmakeApp flow)
#include <core/SHostWnd.h>

#include "soui_board.h"

#include "soui_demo.h" // pulls resource.h (declarations only)

// resource.h is generated by uiresbuilder from uires/uires.idx and lives in
// <project>/soui_res/.  INIT_R_DATA makes this TU the one that *defines* the
// UIRES / R tables; every other TU only sees the extern declarations.  It must
// come after the first (plain) inclusion above: the INIT_R_DATA block sits
// outside resource.h's include guards, on purpose.
#define INIT_R_DATA
#include "resource.h"

// The windres COFF blob, embedded by cmake/soui_res.cmake (.rodata.embedded).
//
// These are strong, not weak, on purpose: swinx/src/resapi.cpp only declares
// them weak (so images without resources still link), and a weak undefined
// reference does not pull an archive member in.  Referencing them here keeps
// the blob out of "silently dropped by the linker" territory -- if the blob is
// missing, the link fails instead of booting into "resource not found".
extern "C" const unsigned char _binary_soui_coff_o_start[];
extern "C" const unsigned char _binary_soui_coff_o_end[];

namespace
{
const char *kTag = "soui_app";

// swinx resolves the resource blob through weak linker symbols; any non-NULL
// module handle works (there is no HINSTANCE from WinMain on a bare target).
const HINSTANCE kAppInstance = (HINSTANCE)1;

// The demo layout is deeper than the first-bring-up one (caption + combobox +
// value animators + cairo), so give the UI task room to breathe.  IDF counts
// stacks in BYTES.
const int kUiTaskStackBytes = 49152;
const UBaseType_t kUiTaskPriority = 5;

void soui_ui_task(void *)
{
    ESP_LOGI(kTag, "== SOUI4 on ESP32-S3 (soui_sim demo) ==");

    soui_board_init();

    // 1. SApplication + SAppCfg -- the wizard/CmakeApp bring-up, unchanged.
    //
    //    DoConfig() does what the previous hand-written sequence did, in the
    //    same order:
    //      * creates the render factory          (Render_Gdi -> render-gdi/cairo,
    //                                             statically linked),
    //      * creates and installs the image      (ImgDecoder_Stb ->
    //        decoder into that factory            imgdecoder-stb; PNG skins and
    //                                             <img> need it, SVG does not),
    //      * loads the system theme              (SYS_XML_SKIN, THEME_COLOR,
    //                                             sys editmenu/msgbox), asserting
    //                                             that the resources were found,
    //      * registers the app resource provider with the uidef id
    //        "uidef:xml_init", which parses uidef/init.xml -> values:strings /
    //        values:skin / values:color.
    //
    //    Both descriptors are set: the resource database carries the app uires
    //    and the SOUI system theme side by side, exactly like a PE build, so
    //    the same blob handle serves both providers.
    SNS::SApplication app(kAppInstance);
    SNS::SAppCfg cfg;
    cfg.SetRender(SNS::Render_Gdi)          // render-gdi (cairo), linked statically
        .SetImgDecoder(SNS::ImgDecoder_Stb) // imgdecoder-stb, also static
        .SetSysResPeHandle(kAppInstance)    // system theme from the blob
        .SetAppResPeHandle(kAppInstance);   // app uires from the same blob
    if (!cfg.DoConfig(&app))
    {
        ESP_LOGE(kTag, "SAppCfg::DoConfig failed, aborting UI task");
        vTaskDelete(NULL);
        return;
    }
    ESP_LOGI(kTag, "app ready: render-gdi + imgdecoder-stb + PE resources");
    ESP_LOGI(kTag, "resource blob: %u bytes at %p",
             (unsigned)(_binary_soui_coff_o_end - _binary_soui_coff_o_start),
             (const void *)_binary_soui_coff_o_start);

    // 2. named ids so EVENT_ID_COMMAND(R.id.btn_test, ...) can be resolved from
    //    the *names* in the layout XML.  R.name / R.id come from uiresbuilder's
    //    resource.h, same table a wizard app uses.
    const int nNamedIds = (int)(sizeof(R.id) / sizeof(int));
    app.InitXmlNamedID((const LPCWSTR *)&R.name, (const int *)&R.id, nNamedIds);
    ESP_LOGI(kTag, "named ids registered: %d", nNamedIds);

    // 3. main window + first frame (WM_INITDIALOG -> images + animators, then a
    //    synchronous WM_PAINT -> framebuffer -> SPI present).
    HWND hWnd = soui_demo_create_window(&app);
    if (!hWnd)
    {
        ESP_LOGE(kTag, "main window creation failed");
        vTaskDelete(NULL);
        return;
    }
    ESP_LOGI(kTag, "main window up, hwnd=%p", (void *)hWnd);

    // 4. non-blocking message pump (a blocking GetMessage() would starve the
    //    board/touch polling and IDF's idle task on this core).
    //
    // Pump budget -- why it exists:
    //   SOUI's value animators request a frame every 16ms, but one repaint on
    //   this board costs tens to hundreds of milliseconds (cairo software
    //   rendering + polled SPI).  Draining the queue in one go therefore keeps
    //   this task runnable for seconds, IDLE1 never runs and the task watchdog
    //   fires ("task_wdt: CPU 1: soui_ui").  Capping both the message count and
    //   the wall time per round guarantees the idle task gets scheduled; the
    //   animation simply runs at whatever rate the panel can sustain.
    //
    // Input priority -- why it is a separate pass:
    //   Even with the timer coalescing in SConnection::updateMsgQueue() the
    //   queue can hold a pending WM_PAINT (which costs a full frame) ahead of
    //   the DOWN that the user just produced.  Peeking the mouse range first
    //   makes a tap cost at most one already-running frame instead of a full
    //   queue turn -- this is what makes the panel feel like the LVGL build.
    const int kMaxInputMsgsPerRound = 6;
    const int kMaxMsgsPerRound = 8;
    const TickType_t kMaxTicksPerRound = pdMS_TO_TICKS(200);

    SNS::IMessageLoop *pMsgLoop = app.GetMsgLoop();
    ESP_LOGI(kTag, "IMessageLoop=%p", (void *)pMsgLoop);
    MSG msg;
    uint32_t nLastPresent = 0;
    uint32_t nLastPixels = 0;
    uint32_t nLastRects = 0;
    uint64_t nLastFlushUs = 0;
    TickType_t tLastReport = xTaskGetTickCount();

    // Paint timing: the SPI push is only ~3ms of a frame, so the 3s report
    // needs to separate "render" (this) from "bus" (flush) to point at the
    // right bottleneck.  WM_PAINT is the only message that renders.
    uint64_t nPaintUs = 0;
    uint32_t nPaintCount = 0;
    uint64_t nLastPaintUs = 0;
    uint32_t nLastPaintCount = 0;

    auto dispatch = [&](MSG &m)
    {
        const bool isPaint = (m.message == WM_PAINT);
        const int64_t t0 = isPaint ? esp_timer_get_time() : 0;
        if (pMsgLoop)
            pMsgLoop->OnMsg(&m);
        else
        {
            TranslateMessage(&m);
            DispatchMessage(&m);
        }
        if (isPaint)
        {
            nPaintUs += (uint64_t)(esp_timer_get_time() - t0);
            ++nPaintCount;
            // One finished frame, for the demo's fps label.
            soui_board_frame_tick();
        }
    };
    while (IsWindow(hWnd))
    {
        // Replay the samples captured by the touch task while this thread was
        // painting.  Cheap (a queue drain), so it runs before anything else.
        soui_board_poll_touch(hWnd);

        const TickType_t tRound = xTaskGetTickCount();
        int nMsgs = 0;

        // 1) input first
        while (nMsgs < kMaxInputMsgsPerRound &&
               PeekMessage(&msg, NULL, WM_MOUSEFIRST, WM_MOUSELAST, PM_REMOVE))
        {
            dispatch(msg);
            ++nMsgs;
        }

        // 2) everything else (paint, timers, commands) under the budget
        while (nMsgs < kMaxMsgsPerRound && PeekMessage(&msg, NULL, 0, 0, PM_REMOVE))
        {
            dispatch(msg);
            ++nMsgs;
            if ((xTaskGetTickCount() - tRound) > kMaxTicksPerRound)
                break;
        }

        // Liveness report: how many dirty-rect blits actually reached the
        // panel in the last 3s (a static screen prints 0 here, which is
        // exactly what makes it useful).  flush_us is the part of that time
        // spent on the SPI wire; the remainder is cairo + the RGB565 convert
        // pass, i.e. what to optimise next if frames are still slow.
        if ((xTaskGetTickCount() - tLastReport) >= pdMS_TO_TICKS(3000))
        {
            const uint32_t nPresent = soui_board_present_count();
            const uint32_t nPixels = soui_board_present_pixels();
            const uint32_t nRects = soui_board_flush_rects();
            const uint64_t nFlushUs = soui_board_flush_us();
            const uint32_t dRects = nRects - nLastRects;
            const uint32_t dPix = nPixels - nLastPixels;
            const double flushMs = dRects ? (double)(nFlushUs - nLastFlushUs) / 1000.0 / dRects : 0.0;
            const uint32_t dPaints = nPaintCount - nLastPaintCount;
            const double paintMs = dPaints ? (double)(nPaintUs - nLastPaintUs) / 1000.0 / dPaints : 0.0;
            const double pixelKps = (double)dPix / 3000.0;  // px/ms == kpx/s
            // nPaintCount == soui_board_frame_count(): both count finished
            // WM_PAINTs.  Report fps directly from it -- "presents" is a blit
            // count (one frame can emit 2 when windows overlap), so dividing
            // presents by seconds over-reports the frame rate by ~1.8x.
            const double fps = (double)dPaints / 3.0;
            const double presPerFrame = dPaints ? (double)(nPresent - nLastPresent) / dPaints : 0.0;
            ESP_LOGI(kTag, "fps=%.1f, paint=%.1fms, flush=%.1fms | presents=%u (+%u/3s, %.2f/frame), pixels=%u (+%u/3s), %.0f kpix/s",
                     fps, paintMs, flushMs,
                     (unsigned)nPresent, (unsigned)(nPresent - nLastPresent), presPerFrame,
                     (unsigned)nPixels, (unsigned)dPix, pixelKps);
            nLastPresent = nPresent;
            nLastPixels = nPixels;
            nLastRects = nRects;
            nLastFlushUs = nFlushUs;
            nLastPaintUs = nPaintUs;
            nLastPaintCount = nPaintCount;
            tLastReport = xTaskGetTickCount();
        }

        // One tick, not ten.  With CONFIG_FREERTOS_HZ=1000 a tick is 1ms, which
        // is the granularity of the input path now: a tap is picked up by the
        // sampler within 8ms and replayed at the top of the next round, so this
        // sleep is the last thing between the finger and the paint.  It still
        // yields to IDLE1 (the task watchdog's condition) -- it just does so
        // for 1ms instead of 10ms.
        vTaskDelay(1);
    }

    ESP_LOGI(kTag, "main window closed, UI task exits");
    // A FreeRTOS task function must not return.
    vTaskDelete(NULL);
}
} // namespace

extern "C" void app_main(void)
{
    // Pin the UI to the APP CPU: core 0 stays with IDF's system/WiFi tasks,
    // and the SPI/PSRAM-heavy present path does not contend with them.
    BaseType_t rc = xTaskCreatePinnedToCore(soui_ui_task, "soui_ui",
                                            kUiTaskStackBytes, NULL,
                                            kUiTaskPriority, NULL, 1);
    if (rc != pdPASS)
        ESP_LOGE(kTag, "failed to create soui_ui task (%d)", (int)rc);
}
